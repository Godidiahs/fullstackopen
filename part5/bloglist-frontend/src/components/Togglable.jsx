import { useState, useImperativeHandle, forwardRef } from 'react'
import PropTypes from 'prop-types'

// Full Stack Open Part 5, exercises 5.4-5.6, 5.13
// A component that hides its children behind a button until the
// button is clicked. App uses a ref to hide the blog form after
// a blog is created, so toggleVisibility is exposed with
// useImperativeHandle.

const Togglable = forwardRef(({ buttonLabel, children }, refs) => {
  const [visible, setVisible] = useState(false)

  const hideWhenVisible = { display: visible ? 'none' : '' }
  const showWhenVisible = { display: visible ? '' : 'none' }

  const toggleVisibility = () => setVisible(!visible)

  useImperativeHandle(refs, () => ({ toggleVisibility }))

  return (
    <div>
      <div style={hideWhenVisible}>
        <button onClick={toggleVisibility}>{buttonLabel}</button>
      </div>
      <div style={showWhenVisible} className="togglableContent">
        {children}
        <button onClick={toggleVisibility}>cancel</button>
      </div>
    </div>
  )
})

Togglable.displayName = 'Togglable'

Togglable.propTypes = {
  buttonLabel: PropTypes.string.isRequired,
}

export default Togglable
